package com.westfield.api.billing.edge.adapter.out.build;

import com.westfield.api.billing.edge.domain.info.BuildInformation;
import com.westfield.api.billing.platform.observability.MigratedFrom;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.info.BuildProperties;
import org.springframework.stereotype.Component;

import java.time.Clock;
import java.time.OffsetDateTime;

/**
 * Reads the build provenance baked into the artifact at package time (N-0011, N-0044).
 *
 * <p>The legacy keeps this in a checked-in {@code buildInfo.properties} carrying Maven filter tokens
 * that an unfiltered build never substitutes; the property then resolves SUCCESSFULLY to its own
 * token text, so the {@code '0'}/{@code '--'} defaults never fire and {@code /info} reports
 * {@code @pomBuildNumber@} (N-0011 ec). Here the values come from
 * {@code META-INF/build-info.properties}, generated by the build itself, and
 * {@link #validateNoUnsubstitutedTokens()} turns the residual possibility into a startup failure
 * rather than a runtime surprise (ADR-0018, INF-001-c).
 */
@Component
@MigratedFrom(value = "km:node/N-0011", note = "buildInfo.properties; token substitution now fails the build")
public class BuildMetadataAdapter {

    private final ObjectProvider<BuildProperties> buildProperties;
    private final Clock clock;
    private final String gitCommit;

    public BuildMetadataAdapter(ObjectProvider<BuildProperties> buildProperties,
                                Clock clock,
                                @Value("${billing.build.git-commit:}") String gitCommit) {
        this.buildProperties = buildProperties;
        this.clock = clock;
        this.gitCommit = gitCommit;
    }

    @MigratedFrom(value = "km:node/N-0044", note = "'0'/'--' defaults; explicit offset on the timestamp")
    public BuildInformation current() {
        BuildProperties properties = buildProperties.getIfAvailable();
        String buildNumber = properties == null ? null : properties.get("number");
        String buildName = properties == null ? null : properties.getName();
        String other = properties == null ? null : properties.getVersion();
        return BuildInformation.of(buildNumber, buildName, gitCommit, other, OffsetDateTime.now(clock));
    }

    /**
     * An unsubstituted build-tool token must never reach a caller. ADR-0018 asks for this by name:
     * the silent failure mode becomes a loud one.
     */
    public void validateNoUnsubstitutedTokens() {
        BuildInformation information = current();
        for (String value : new String[]{information.buildNumber(), information.buildName(),
                information.gitCommit(), information.otherBuildInfo()}) {
            if (BuildInformation.isUnsubstitutedToken(value)) {
                throw new IllegalStateException(
                        "Build metadata contains an unsubstituted build-tool token: '" + value
                                + "'. The build must substitute it; /info must never serve it (ADR-0018).");
            }
        }
    }
}
